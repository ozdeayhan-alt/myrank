export function getFilterOptions(
  key: keyof RankedUser,
  users: RankedUser[] = RANKING_USERS,
): string[] {
  const values = new Set(users.map((u) => String(u[key as keyof RankedUser])))
  return Array.from(values).sort((a, b) => a.localeCompare(b, 'tr'))
}
